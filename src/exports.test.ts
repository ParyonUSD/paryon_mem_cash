describe("entry points", () => {
	it("'.' exports every value of the five 0.0.9 packages, and nothing else", () => {
		expect(Object.keys(root).sort()).toEqual(values);
	});

	it("'./validation' exports what @mem-cash/validation 0.0.9 did, and the fork's additions", () => {
		expect(Object.keys(validation).sort()).toEqual(validationValues);
	});

	it("'.' gives AddUtxoParams to the node, and the storage helper's its own name", () => {
		// Both core and storage exported an AddUtxoParams. The node's is the one a consumer of the
		// whole node passes to addUtxo, so it keeps the name.
		expectTypeOf<AddUtxoParams>().toEqualTypeOf<NodeAddUtxoParams>();
		expectTypeOf<StorageAddUtxoParams>().toEqualTypeOf<StorageHelperAddUtxoParams>();
	});
});
